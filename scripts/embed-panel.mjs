import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const html = await readFile(resolve(root, "web/dist/index.html"), "utf8");
const moduleText = `// Generated by scripts/embed-panel.mjs.\nexport const PANEL_HTML = ${JSON.stringify(html)};\n`;
await writeFile(resolve(root, "src/mcp/panel-html.generated.ts"), moduleText);
console.log(`Embedded panel: ${new TextEncoder().encode(html).byteLength} bytes`);
